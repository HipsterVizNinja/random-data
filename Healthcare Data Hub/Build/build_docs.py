def read_head(path: Path, n: int = 400) -> pd.DataFrame:
    return pd.read_csv(path, nrows=n, low_memory=False)


def count_rows(path: Path) -> int:
    with gzip.open(path, "rt") as fh:
        return sum(1 for _ in fh) - 1


def infer_type(s: pd.Series) -> str:
    if pd.api.types.is_bool_dtype(s):
        return "boolean"
    if pd.api.types.is_integer_dtype(s):
        return "integer"
    if pd.api.types.is_float_dtype(s):
        return "decimal"
    sample = s.dropna().astype(str).head(40)
    if len(sample) and sample.str.fullmatch(r"\d{4}-\d{2}-\d{2}").all():
        return "date"
    return "string"


def build_data_dictionary() -> None:
    L = ["# Data dictionary", "",
         "Generated by `Build/build_docs.py` from the shipped files. Row counts "
         "and column types are measured, not asserted.", "",
         f"**Classification:** SYNTHETIC. {C.SYNTHETIC_NOTICE}", ""]
    groups = [("Source data", sorted(RAW.rglob("*.csv.gz"))),
              ("Mart", sorted(MART.glob("*.csv.gz")))]
    for title, paths in groups:
        L += [f"## {title}", ""]
        for path in paths:
            name = path.name.replace(".csv.gz", "")
            if name.endswith("_truth"):
                continue
            df = read_head(path)
            rows = count_rows(path)
            rel = path.relative_to(ROOT)
            L += [f"### `{name}`", ""]
            if name in TABLE_PURPOSE:
                L += [TABLE_PURPOSE[name], ""]
            L += [f"`{rel}` — {rows:,} rows, {len(df.columns)} columns", "",
                  "| Column | Type | Example |", "|---|---|---|"]
            for col in df.columns:
                ex = df[col].dropna()
                ex = str(ex.iloc[0])[:40] if len(ex) else ""
                ex = ex.replace("|", "\\|")
                L.append(f"| `{col}` | {infer_type(df[col])} | {ex} |")
            L.append("")
    (DOCS / "data-dictionary.md").write_text("\n".join(L) + "\n")
    print(f"  wrote {DOCS / 'data-dictionary.md'}")


def _fmt(v, indent=0):
    pad = "  " * indent
    if isinstance(v, dict):
        out = []
        for k, val in v.items():
            if isinstance(val, (dict, list)):
                out.append(f"{pad}- **{k}**")
                out.append(_fmt(val, indent + 1))
            else:
                out.append(f"{pad}- **{k}**: {val}")
        return "\n".join(out)
    if isinstance(v, list):
        return "\n".join(f"{pad}- {x}" for x in v)
    return f"{pad}{v}"


def build_answer_key() -> None:
    man = json.loads((DELIV / "anomaly-manifest.json").read_text())
    L = ["# Anomaly answer key", "",
         "**Do not hand this to a demo audience before the reveal.** It gives "
         "away every planted defect and its magnitude.", "",
         "This file is generated by `Build/build_docs.py` from "
         "`anomaly-manifest.json`, which the build itself produces. Every "
         "figure below was measured on the data that shipped, so the answer "
         "key cannot drift from the dataset.", "",
         f"**Scale:** {man['scale']} — {man['members']:,} members  ",
         f"**Seed:** {man['seed']}  ",
         f"**Anomalies applied:** {man['anomalies_applied']}", "",
         "The companion document, "
         "[data-trust-validation.md](data-trust-validation.md), is the "
         "client-facing artifact: it proves the defects were found and "
         "controlled without giving away how. This one is the teaching "
         "artifact.", "",
         "---", ""]
    for a in man["anomalies"]:
        if not a.get("applied", False):
            L += [f"## {a.get('anomaly_id', '?')} — {a.get('name', '')}", "",
                  a.get("description", ""), ""]
            continue
        L += [f"## {a['anomaly_id']} — {a['name']}", ""]
        if a.get("description"):
            L += [a["description"], ""]
        for label, key in (("Measured", "measured"), ("Naive error", "naive_error")):
            if a.get(key):
                L += [f"**{label}**", "", _fmt(a[key]), ""]
        for label, key in (("Rows added", "rows_added"),
                           ("Rows affected", "rows_affected"),
                           ("Concentration site", "concentration_site"),
                           ("Affected service month", "affected_service_month")):
            if a.get(key) is not None:
                L += [f"**{label}:** {a[key]:,}" if isinstance(a[key], int)
                      else f"**{label}:** {a[key]}", ""]
        if a.get("detect"):
            L += ["**How to detect it**", "", a["detect"], ""]
        if a.get("control"):
            L += ["**How to control for it**", "", a["control"], ""]
        L += ["---", ""]
    L += ["## The clean twin", "",
          "```sh", "python Generators/build.py --scale demo --no-anomalies",
          "```", "",
          "Run any analysis against both datasets. The delta *is* the trap, "
          "and showing it that way is more convincing than any explanation of "
          "the mechanism."]
    (DELIV / "anomaly-answer-key.md").write_text("\n".join(L) + "\n")
    print(f"  wrote {DELIV / 'anomaly-answer-key.md'}")


